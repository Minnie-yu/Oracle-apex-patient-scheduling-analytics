/* =====================================================
   1. DATABASE OBJECTS: TABLES
   ===================================================== */

CREATE TABLE patients (
    patient_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    date_of_birth DATE NOT NULL,
    phone_number VARCHAR2(20),
    CONSTRAINT patients_pk PRIMARY KEY (patient_id)
);

CREATE TABLE providers (
    provider_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    provider_name VARCHAR2(100) NOT NULL,
    specialty VARCHAR2(100) NOT NULL,
    CONSTRAINT providers_pk PRIMARY KEY (provider_id),
    CONSTRAINT providers_specialty_ck CHECK (
        specialty IN (
            'Cardiology',
            'Primary Care',
            'Dermatology',
            'Neurology',
            'Orthopedics',
            'Pediatrics'
        )
    )
);

CREATE TABLE appointments (
    appointment_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    patient_id NUMBER NOT NULL,
    provider_id NUMBER NOT NULL,
    appointment_date DATE NOT NULL,
    status VARCHAR2(20) NOT NULL,
    CONSTRAINT appointments_pk PRIMARY KEY (appointment_id),
    CONSTRAINT appointments_patient_fk FOREIGN KEY (patient_id)
        REFERENCES patients(patient_id),
    CONSTRAINT appointments_provider_fk FOREIGN KEY (provider_id)
        REFERENCES providers(provider_id),
    CONSTRAINT appointments_status_ck CHECK (
        status IN ('Scheduled', 'Completed', 'No-Show', 'Cancelled')
    )
);


