/* =====================================================
   5. VIEW FOR PAGE 1: INTERACTIVE REPORT
   Required columns:
   Patient Name, Provider Name, Specialty, Appointment Date, Appointment Status
   ===================================================== */

CREATE OR REPLACE VIEW appointment_report_v AS
SELECT
    a.appointment_id,
    p.first_name || ' ' || p.last_name AS patient_name,
    pr.provider_name,
    pr.specialty,
    a.appointment_date,
    a.status AS appointment_status
FROM appointments a
JOIN patients p
    ON a.patient_id = p.patient_id
JOIN providers pr
    ON a.provider_id = pr.provider_id;


/* =====================================================
   6. VIEW FOR CHART 1: NO-SHOW RATE
   This supports a pie chart named "No-Show Rate".
   It shows No-Show and other appointment statuses as proportions.
   ===================================================== */

CREATE OR REPLACE VIEW no_show_rate_v AS
SELECT
    status AS appointment_status,
    COUNT(*) AS appointment_count,
    ROUND(
        COUNT(*) * 100 / NULLIF((SELECT COUNT(*) FROM appointments), 0),
        2
    ) AS status_percentage
FROM appointments
GROUP BY status;


/* =====================================================
   7. VIEW FOR CHART 2: APPOINTMENTS PER PROVIDER
   ===================================================== */

CREATE OR REPLACE VIEW provider_utilization_v AS
SELECT
    pr.provider_name,
    pr.specialty,
    COUNT(a.appointment_id) AS total_appointments
FROM providers pr
LEFT JOIN appointments a
    ON pr.provider_id = a.provider_id
GROUP BY pr.provider_name, pr.specialty;


/* =====================================================
   8. VIEW FOR CHART 3: DAILY APPOINTMENT TRENDS
   ===================================================== */

CREATE OR REPLACE VIEW daily_appointment_trends_v AS
SELECT
    TRUNC(appointment_date) AS appointment_day,
    COUNT(*) AS total_appointments
FROM appointments
GROUP BY TRUNC(appointment_date);


/* =====================================================
   9. ANALYTICS QUERIES
   These are required for Deliverable 1.
   ===================================================== */

/* No-Show Rate Analysis */
SELECT
    appointment_status,
    appointment_count,
    status_percentage
FROM no_show_rate_v
ORDER BY appointment_status;

/* Provider Utilization */
SELECT
    provider_name,
    specialty,
    total_appointments
FROM provider_utilization_v
ORDER BY provider_name;

/* Daily Appointment Trends */
SELECT
    appointment_day,
    total_appointments
FROM daily_appointment_trends_v
ORDER BY appointment_day;


